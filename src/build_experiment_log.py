"""Auto-generate EXPERIMENT_LOG.md from meta.json + aligned.json across all versioned runs.

Walks output/{slug}/versions/*/{meta.json, aligned.json} and emits one row per
(doc, version) tuple with the fields that answer 'what did we try, what were
the numbers?' — the notes doc's experiment-journal ask.

Run: python3 -m src.build_experiment_log
Writes: EXPERIMENT_LOG.md at the repo root.
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

_THIS_FILE = Path(__file__).resolve()
_PROJECT_ROOT = _THIS_FILE.parent.parent
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from src.registry import discover_docs
from src.strategies import STRATEGIES


def _row(doc, version_id: str) -> dict | None:
    v_dir = doc.paths["out_dir"] / "versions" / version_id
    meta_path = v_dir / "meta.json"
    aligned_path = v_dir / "aligned.json"
    if not meta_path.exists() or not aligned_path.exists():
        return None
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    aligned = json.loads(aligned_path.read_text(encoding="utf-8"))
    c = aligned.get("counts", {})

    ai_total = c.get("ai_total", 0)
    caught = c.get("anchors_with_ai_and_human", 0)
    total_human = c.get("anchors_with_human", 0) + c.get("human_unmatched", 0)
    missed = max(0, total_human - caught)

    strategy = STRATEGIES.get(version_id)
    display = meta.get("display_label") or (strategy.label() if strategy else version_id)

    return {
        "slug": doc.slug,
        "version_id": version_id,
        "display_label": display,
        "workflow": meta.get("workflow", ""),
        "chunker": meta.get("chunker", ""),
        "chunker_params": meta.get("chunker_params", {}),
        "prompt_builder": meta.get("prompt_builder", ""),
        "model": meta.get("model", ""),
        "n_chunks": meta.get("n_chunks", ""),
        "created_at": meta.get("created_at", ""),
        "ai_total": ai_total,
        "anchors_caught": caught,
        "anchors_missed": missed,
        "human_total_anchors": total_human,
    }


def _format_params(p) -> str:
    if not p:
        return ""
    if isinstance(p, dict):
        return ", ".join(f"{k}={v}" for k, v in p.items())
    return str(p)


def build_markdown(rows: list[dict]) -> str:
    """Emit the EXPERIMENT_LOG.md content."""
    header = [
        "# Experiment log",
        "",
        "Auto-generated by `python3 -m src.build_experiment_log`. Do not edit by hand — regenerate.",
        "",
        f"**Total (doc, version) runs recorded:** {len(rows)}",
        "",
    ]

    # Group by slug for readability.
    by_slug: dict[str, list[dict]] = {}
    for r in rows:
        by_slug.setdefault(r["slug"], []).append(r)

    for slug in sorted(by_slug.keys()):
        doc_rows = sorted(by_slug[slug], key=lambda r: r["version_id"])
        header.append(f"## {slug}")
        header.append("")
        header.append("| Version | Workflow | Chunker | Prompt rules | Model | AI tags | Caught | Missed | Created |")
        header.append("|---|---|---|---|---|---:|---:|---:|---|")
        for r in doc_rows:
            chunker_str = r["chunker"]
            if r["chunker_params"]:
                chunker_str += f" ({_format_params(r['chunker_params'])})"
            header.append(
                f"| **{r['display_label']}** "
                f"| {r['workflow']} "
                f"| {chunker_str} "
                f"| {r['prompt_builder']} "
                f"| {r['model']} "
                f"| {r['ai_total']} "
                f"| {r['anchors_caught']} "
                f"| {r['anchors_missed']} "
                f"| {r['created_at'][:10]} |"
            )
        header.append("")

    header.append("## How to read this table")
    header.append("")
    header.append("- **AI tags** — total annotations the AI emitted for that doc under that strategy.")
    header.append("- **Caught** — human-tagged anchors the AI also tagged (any category overlap).")
    header.append("- **Missed** — human-tagged anchors the AI did not tag at all (includes anchors whose sentence text couldn't be aligned to the doc).")
    header.append("- The Netlify site's *Missed Human Tags* tab per version shows exactly which anchors, why they were lost (for V3 and V5), and the sentence + human tag.")
    header.append("")
    return "\n".join(header)


def main() -> None:
    docs = discover_docs()
    rows: list[dict] = []
    for doc in docs:
        for vid in doc.versions:
            row = _row(doc, vid)
            if row:
                rows.append(row)

    md = build_markdown(rows)
    out = _PROJECT_ROOT / "EXPERIMENT_LOG.md"
    out.write_text(md, encoding="utf-8")
    print(f"wrote {out} ({len(rows)} rows across {len(set(r['slug'] for r in rows))} docs)")


if __name__ == "__main__":
    main()
